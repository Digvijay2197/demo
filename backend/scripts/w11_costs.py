"""Week 11: cost-per-query by stage + the 10x question, computed from the logs.

    python scripts/w11_costs.py --trace tr_6988ef145c4d   # writes docs/week11/cost_by_stage.md + tenx.md

Every figure comes from logs/traces.jsonl (per-span tokens/latency/cost) so
nothing here is hand-typed. Prices are the ASSUMED Groq list prices in
rag/config.py (the free tier bills $0).
"""
import argparse
import json
import math
import os
import statistics
import sys
from collections import Counter
from datetime import datetime

sys.path.insert(0, os.getcwd())
from rag.config import GROQ_MODEL, PRICE_IN_PER_M, PRICE_OUT_PER_M  # noqa: E402
from rag.generation.prompt import DIETARY_REMINDER, PROMPTS  # noqa: E402
from rag.observability.dairy_check import restriction_stated  # noqa: E402

DOCS = os.path.abspath(os.path.join(os.getcwd(), "..", "docs", "week11"))
GROQ_TPM, GROQ_TPD = 8_000, 200_000  # free-tier ceilings seen in the 429 bodies


def pct(xs, q):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, math.ceil(q * len(xs)) - 1)]


def stage_cost(rec, name):
    return sum(s["cost_usd"] for s in rec["spans"] if s["name"] == name)


def stage_ms(rec, name):
    return sum(s["latency_ms"] for s in rec["spans"] if s["name"] == name)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--trace", required=True)
    a = ap.parse_args()
    rows = [json.loads(line) for line in open("logs/traces.jsonl", encoding="utf-8")]
    one = next(r for r in rows if r["trace_id"] == a.trace)
    gen = next(s for s in one["spans"] if s["name"] == "generation")
    total = one["cost_usd"]

    # ---------------- per-request breakdown ----------------
    def line(stage, label, note):
        c, ms = stage_cost(one, stage), stage_ms(one, stage)
        share = 100 * c / total if total else 0
        return f"| {label} | {ms:.1f} ms | ${c:.8f} | {share:.1f}% | {note} |"

    in_cost = gen["tokens_in"] * PRICE_IN_PER_M / 1e6
    out_cost = gen["tokens_out"] * PRICE_OUT_PER_M / 1e6
    delta_chars = len(PROMPTS["v2"]) - len(PROMPTS["v1"])
    delta_tok = round(delta_chars / 4)  # ~4 chars/token - an ESTIMATE, replaced if a measured v2 trace exists
    v2_cost = total + delta_tok * PRICE_IN_PER_M / 1e6
    rem_tok = round(len(DIETARY_REMINDER) / 4)               # v3: reminder, restricted questions only
    v3_cost = total + rem_tok * PRICE_IN_PER_M / 1e6

    # ---------------- population stats ----------------
    n = len(rows)
    gens = [stage_cost(r, "generation") for r in rows]
    tot = [r["cost_usd"] for r in rows]
    tok = [r["tokens_in"] + r["tokens_out"] for r in rows]
    days = Counter(r["ts"][:10] for r in rows)
    per_min = Counter(r["ts"][:16] for r in rows)
    peak_min, peak_n = per_min.most_common(1)[0]
    avg_day = statistics.mean(days.values())
    avg_tok = statistics.mean(tok)
    lat95 = pct([r["latency_ms"] for r in rows], 0.95)
    lat50 = pct([r["latency_ms"] for r in rows], 0.50)
    mean_cost = statistics.mean(tot)
    restricted_share = sum(1 for r in rows if restriction_stated(r["question"])) / n
    ret_ms = statistics.mean(stage_ms(r, "retrieval") for r in rows)
    gen_ms = statistics.mean(stage_ms(r, "generation") for r in rows)
    tool_ms = statistics.mean(stage_ms(r, "tools") for r in rows)

    md = f"""<!-- Week 11 · Task Set B · cost_by_stage.md — generated by scripts/w11_costs.py from logs/traces.jsonl -->
# Cost per query, by stage

Request: `{one['trace_id']}` — *"{one['question']}"* · model `{one['model']}` · prompt `{one['prompt_version']}`
Pricing used (assumed Groq list price, **not** what the free tier bills — it bills $0): ${PRICE_IN_PER_M}/M input, ${PRICE_OUT_PER_M}/M output tokens.

| stage | latency | cost | share of cost | what it is |
|---|---|---|---|---|
{line('retrieval', 'retrieval', 'local MiniLM embedding + Chroma + BM25 — no per-call bill; it costs CPU time, not dollars')}
{line('generation', 'generation', f"{gen['tokens_in']} in + {gen['tokens_out']} out tokens ({gen.get('reasoning_tokens', 0)} reasoning)")}
{line('tools', 'tools', 'citation matching/resolution — in-process Python, no external call')}
| **total** | **{one['latency_ms']:.1f} ms** | **${total:.8f}** | 100% | |

Generation split: input `{gen['tokens_in']}` tok × ${PRICE_IN_PER_M}/M = **${in_cost:.8f}** ({100*in_cost/total:.0f}%), output `{gen['tokens_out']}` tok × ${PRICE_OUT_PER_M}/M = **${out_cost:.8f}** ({100*out_cost/total:.0f}%).
So input tokens (the retrieved context + system prompt) are where the money is — which is why `MAX_CONTEXT_CHARS` is the lever, not the answer length.

## Across the whole week of logs ({n} requests)

| | mean | p50 | p95 |
|---|---|---|---|
| cost / query | ${mean_cost:.8f} | ${pct(tot, .5):.8f} | ${pct(tot, .95):.8f} |
| tokens / query (in+out) | {avg_tok:,.0f} | {pct(tok, .5):,} | {pct(tok, .95):,} |
| latency | {statistics.mean(r['latency_ms'] for r in rows):.0f} ms | {lat50:.0f} ms | {lat95:.0f} ms |

Mean latency by stage: retrieval {ret_ms:.0f} ms · generation {gen_ms:.0f} ms · tools {tool_ms:.2f} ms.
**Generation is {100*statistics.mean(gens)/mean_cost:.1f}% of dollars and {100*gen_ms/(ret_ms+gen_ms+tool_ms):.0f}% of time.**

## What the prompt fix costs (v1 → v3, shipped)

v3 leaves the system prompt **byte-identical to v1** and adds a short dietary reminder next to the question, **only when the question states a dairy restriction**:
**+{len(DIETARY_REMINDER)} characters ≈ +{rem_tok} input tokens** (≈4 chars/token — an *estimate*).

| | per query | this request | across the week of logs |
|---|---|---|---|
| v1 (before) | ${total:.8f} | ${total:.8f} | mean ${mean_cost:.8f} |
| **v3 (shipped)** | +${rem_tok * PRICE_IN_PER_M / 1e6:.8f} on restricted questions only | **≈ ${v3_cost:.8f}** (+{100*(v3_cost-total)/total:.1f}%) | mean ≈ ${mean_cost + restricted_share * rem_tok * PRICE_IN_PER_M / 1e6:.8f} (+{100*restricted_share * rem_tok * PRICE_IN_PER_M / 1e6 / mean_cost:.2f}% — only {100*restricted_share:.1f}% of queries state a restriction) |
| v2 (tried, rejected) | +{delta_tok} tok on **every** query ≈ +${delta_tok * PRICE_IN_PER_M / 1e6:.8f} | ≈ ${v2_cost:.8f} (+{100*(v2_cost-total)/total:.1f}%) | mean ≈ +{100*delta_tok * PRICE_IN_PER_M / 1e6 / mean_cost:.1f}% |

So the shipped fix costs about **${rem_tok * PRICE_IN_PER_M / 1e6:.7f} extra on the queries that need it** — effectively free on average.
*Caveat:* the {100*restricted_share:.0f}% restricted share is an artefact of the simulated log (half of the real pool I resampled from were deliberately dietary probes); real traffic would have far fewer, so the true average bump is **below** the figure in the table. (Prompt caching of the static system prompt would shave the baseline too — not turned on.)

> I deliberately did **not** optimise anything this week before attributing cost by stage (the "common mistake" in the brief):
> the stage table above is the attribution; the only change made to cost is the +{rem_tok}-token conditional reminder, and its effect is stated above.
"""
    open(os.path.join(DOCS, "cost_by_stage.md"), "w", encoding="utf-8").write(md)

    # ---------------- 10x ----------------
    max_qpm = GROQ_TPM / avg_tok
    max_qpd = GROQ_TPD / avg_tok
    peak_tpm_1x = peak_n * avg_tok
    peak_tpm_10x = 10 * peak_tpm_1x
    day_cost_10x = 10 * avg_day * mean_cost
    tenx = f"""<!-- Week 11 · Task Set B · tenx.md — generated by scripts/w11_costs.py -->
# What breaks first at 10x?

**Rate limit — at 10x the busiest minute needs {peak_tpm_10x:,.0f} tokens/min against the {GROQ_TPM:,} tokens/min ceiling ({peak_tpm_10x/GROQ_TPM:.1f}x over), while cost is only ${day_cost_10x:.2f}/day and p95 latency is unchanged at {lat95/1000:.1f}s.**

The numbers behind the line (all from the {n}-request week of logs):

| | today (1x) | 10x | limit | verdict |
|---|---|---|---|---|
| queries / day | {avg_day:.0f} | {10*avg_day:,.0f} | {max_qpd:.0f}/day at {avg_tok:,.0f} tok/query (200k TPD) | **{10*avg_day/max_qpd:.1f}x over** (1x is already {avg_day/max_qpd:.1f}x over) |
| busiest minute ({peak_min[11:]} UTC) | {peak_n} queries = {peak_tpm_1x:,.0f} tok/min | {10*peak_n} queries = {peak_tpm_10x:,.0f} tok/min | {GROQ_TPM:,} tok/min = {max_qpm:.1f} queries/min | **{peak_tpm_10x/GROQ_TPM:.1f}x over** |
| cost / day | ${avg_day*mean_cost:.3f} | ${day_cost_10x:.2f} | none (no budget set) | fine — ${day_cost_10x*30:.0f}/month |
| p95 latency | {lat95/1000:.2f} s | {lat95/1000:.2f} s | no SLO set (sub-5 s assumed) | fine *until* 429s: each 429 retry sleeps and adds seconds |

Why this order: cost scales linearly and tiny (${mean_cost:.6f}/query); latency is per-request and doesn't grow with volume
unless something queues — and the only thing that queues is the rate limiter. This is not hypothetical: I hit the 200k-tokens/day cap
while running this very week's evals (`429 … on tokens per day (TPD): Limit 200000, Used 199123`), which is why the GREEN run is
written to wait out the limit (`eval_week6.py --patient`).

**Caveat on "today":** the week of traffic in `logs/traces.jsonl` is *simulated* (resampled from {sum(1 for _ in open('logs/real_pool.jsonl', encoding='utf-8'))} real traces
at ~220 queries/day) — this demo app has no real users. So the "1x" column is only as real as that assumption; the **ceiling column is
measured** ({max_qpm:.1f} queries/min and {max_qpd:.0f} queries/day at {avg_tok:,.0f} tokens/query) and is what you should quote.

First fix (not built this week): move off the free tier / add a second model behind a fallback (LiteLLM router), shrink input
tokens (`MAX_CONTEXT_CHARS` 4000 → 2500 saves ~{(1-2500/4000)*100:.0f}% of context tokens), and add prompt caching for the static system prompt.
"""
    open(os.path.join(DOCS, "tenx.md"), "w", encoding="utf-8").write(tenx)
    print(f"cost_by_stage.md + tenx.md written. total=${total:.8f} mean=${mean_cost:.8f} "
          f"avg_tok={avg_tok:.0f} peak={peak_n}/min avg_day={avg_day:.0f} p95={lat95:.0f}ms")


if __name__ == "__main__":
    main()
